import logging
from fastapi import FastAPI, Request, HTTPException, BackgroundTasks, Response
from fastapi.middleware.cors import CORSMiddleware
from slack_security import verify_slack_signature
from agent_router import process_and_respond
from config import AGENTS_CONFIG

# Configure logging format
logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s"
)
logger = logging.getLogger("CaiLogicsBackend")

app = FastAPI(
    title="CaiLogics Multi-Agent Slack Hub",
    description="Multi-agent orchestration platform integrating Slack Events API, LiteLLM, and MCP tools.",
    version="1.0.0"
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

@app.get("/")
@app.get("/health")
async def health_check():
    """Basic health check endpoint."""
    return {
        "status": "healthy",
        "service": "CaiLogics Multi-Agent Hub",
        "agents": list(AGENTS_CONFIG.keys())
    }

@app.post("/slack/events")
async def slack_events(request: Request, background_tasks: BackgroundTasks):
    """
    Primary Webhook endpoint receiving Events API payloads from Slack.
    Handles URL verification challenges, security signature checks, deduplication,
    and triggers asynchronous agent completion tasks.
    """
    body_bytes = await request.body()
    headers = request.headers

    # 1. Verify Slack HMAC Signature
    if not verify_slack_signature(body_bytes, headers):
        logger.warning("Rejected unauthorized request to /slack/events")
        raise HTTPException(status_code=401, detail="Invalid Slack signature")

    # 2. Parse JSON payload
    try:
        data = await request.json()
    except Exception as e:
        logger.error(f"Failed to parse JSON body: {e}")
        raise HTTPException(status_code=400, detail="Invalid JSON payload")

    # 3. Handle Slack URL Verification Challenge
    if data.get("type") == "url_verification":
        logger.info("Handling Slack url_verification challenge")
        return {"challenge": data.get("challenge")}

    # 4. Handle Event Callbacks (message.channels, app_mention)
    if data.get("type") == "event_callback":
        event = data.get("event", {})
        bot_user_id = data.get("authed_users", [None])[0] if data.get("authed_users") else None

        # Filter out bot messages to avoid infinite self-loops
        if event.get("bot_id") or event.get("subtype") == "bot_message":
            logger.debug("Skipping message generated by a bot.")
            return Response(status_code=200)

        event_type = event.get("type")
        if event_type in ["message", "app_mention"]:
            channel_id = event.get("channel")
            # If message is inside a thread, use thread_ts; otherwise use message ts
            thread_ts = event.get("thread_ts") or event.get("ts")
            raw_text = event.get("text", "")

            if channel_id and thread_ts and raw_text:
                logger.info(f"Received Slack event '{event_type}' in channel {channel_id}, thread {thread_ts}")
                # Process agent response in background task to return HTTP 200 within 3s limit
                background_tasks.add_task(
                    process_and_respond,
                    channel_id=channel_id,
                    thread_ts=thread_ts,
                    raw_text=raw_text,
                    bot_user_id=bot_user_id
                )

    # Always return HTTP 200 OK immediately to Slack
    return Response(status_code=200)
