import time
from dataclasses import dataclass, field
from typing import Any, Literal


@dataclass
class Turn:
    """Represents a single conversational turn by a user or an agent."""

    role: Literal["user", "assistant", "system"]
    content: str
    speaker: str = "User"
    timestamp: float = field(default_factory=time.time)
    token_usage: dict[str, int] = field(default_factory=dict)
    metadata: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "role": self.role,
            "content": self.content,
            "speaker": self.speaker,
            "timestamp": self.timestamp,
            "token_usage": self.token_usage,
            "metadata": self.metadata,
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Turn":
        return cls(
            role=data.get("role", "user"),
            content=data.get("content", ""),
            speaker=data.get("speaker", "User"),
            timestamp=data.get("timestamp", time.time()),
            token_usage=data.get("token_usage", {}),
            metadata=data.get("metadata", {}),
        )


@dataclass
class SessionContext:
    """
    Platform-agnostic representation of an ongoing multi-agent discussion session.
    Decoupled from specific chat platforms while retaining channel_id and thread_ts metadata.
    """

    session_id: str
    channel_id: str = ""
    thread_ts: str = ""
    history: list[Turn] = field(default_factory=list)
    active_exclusions: list[str] = field(default_factory=list)
    max_words: int | None = None
    min_words: int | None = None
    history_limit: int | None = None
    budget_limit_usd: float | None = None
    language: str = "English"
    metadata: dict[str, Any] = field(default_factory=dict)

    @classmethod
    def from_thread(
        cls,
        channel_id: str,
        thread_ts: str,
        raw_history: list[dict[str, Any]] | None = None,
    ) -> "SessionContext":
        session_id = f"{channel_id}:{thread_ts}"
        history_turns: list[Turn] = []
        if raw_history:
            for item in raw_history:
                if isinstance(item, Turn):
                    history_turns.append(item)
                elif isinstance(item, dict):
                    history_turns.append(Turn.from_dict(item))
        return cls(
            session_id=session_id,
            channel_id=channel_id,
            thread_ts=thread_ts,
            history=history_turns,
        )

    def to_llm_history(self) -> list[dict[str, str]]:
        return [
            {"role": t.role, "content": t.content}
            for t in self.history
        ]

    def add_turn(
        self,
        role: Literal["user", "assistant", "system"],
        content: str,
        speaker: str = "User",
        token_usage: dict[str, int] | None = None,
    ) -> Turn:
        turn = Turn(
            role=role,
            content=content,
            speaker=speaker,
            token_usage=token_usage or {},
        )
        self.history.append(turn)
        return turn



@dataclass
class DiscussionBrief:
    """Structured strategic synthesis generated by the discussion scribe."""

    objective: str = ""
    perspectives: list[str] = field(default_factory=list)
    consensus: str = ""
    risks: list[str] = field(default_factory=list)
    action_items: list[str] = field(default_factory=list)
    is_completed: bool = False
    raw_markdown: str = ""
    language: str = "en"  # "en" or "hr"

    def to_dict(self) -> dict[str, Any]:
        return {
            "objective": self.objective,
            "perspectives": self.perspectives,
            "consensus": self.consensus,
            "risks": self.risks,
            "action_items": self.action_items,
            "is_completed": self.is_completed,
            "raw_markdown": self.raw_markdown,
            "language": self.language,
        }


@dataclass
class DiscussionConclusion:
    """Structured conclusion brief containing problem statement and multi-perspective argumentation."""

    problem_statement: str = ""
    consensus: str = ""
    opposing_conclusions: list[dict[str, Any]] = field(default_factory=list)
    raw_markdown: str = ""
    is_completed: bool = True
    language: str = "en"  # "en" or "hr"

    def to_dict(self) -> dict[str, Any]:
        return {
            "problem_statement": self.problem_statement,
            "consensus": self.consensus,
            "opposing_conclusions": self.opposing_conclusions,
            "raw_markdown": self.raw_markdown,
            "is_completed": self.is_completed,
            "language": self.language,
        }


@dataclass
class SpendMetrics:
    """Monetary and token consumption metrics for a session."""

    session_id: str
    total_prompt_tokens: int = 0
    total_completion_tokens: int = 0
    total_cost_usd: float = 0.0
    cost_by_model: dict[str, float] = field(default_factory=dict)
    tokens_by_model: dict[str, dict[str, int]] = field(default_factory=dict)
    circuit_breaker_tripped: bool = False
